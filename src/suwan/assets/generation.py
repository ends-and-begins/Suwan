def dream_line(fragments: list[str]) -> str:
    if fragments:
        elements = "、".join([f[:20] for f in fragments])
        return f"梦里出现了{elements}，它们以一种奇怪的方式组合在一起。"
    return random.choice(_DREAMS)


def reminisce_narration(memory_text: str) -> str:
    return random.choice(_REMINISCE).format(mem=memory_text[:60])
