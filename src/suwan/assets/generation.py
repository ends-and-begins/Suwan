def learning_note(topic: str) -> str:
    template = random.choice(
        [
            "# {topic}\n\n## 概念\n{topic}是……\n\n## 要点\n- 第一\n- 第二\n\n## 感悟\n这个让我想起……",
            "### 今日学习：{topic}\n\n- 核心思想：\n- 例子：\n- 我的疑问：",
        ]
    )
    return template.format(topic=topic)


